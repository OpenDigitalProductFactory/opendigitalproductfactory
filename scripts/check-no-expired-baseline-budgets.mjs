#!/usr/bin/env node
// scripts/check-no-expired-baseline-budgets.mjs
//
// BI-3F17B16B (Simplify & Strengthen W1, pass §2 / §5 Tier-0 #1 / Phase 6 of
// the 2026-08-01 hardening plan) — baselines are owned, expiring BUDGETS, not
// permanent freezes.
//
// THE PROBLEM IT FIXES: the architecture pass verified the failure live — the
// application-boundary exception baseline sat at 65 entries, unchanged, while
// cross-context imports grew 498 -> 504 in two weeks. A baseline with no owner
// and no expiry converts "debt we intend to burn down" into "debt we have
// legitimized forever", silently.
//
// THE CONTRACT: every ratchet baseline under scripts/ must either
//   (a) carry the house budget shape — owner + expiry (JSON top-level fields,
//       or `# owner:` / `# expiry:` leading comment lines in txt baselines;
//       see scripts/lib/baseline-budget.mjs) — with an UNEXPIRED expiry, or
//   (b) appear on one of the two explicit rosters below:
//       EXEMPT   — files that are not frozen-debt budgets at all (soft
//                  growth-with-reason shapes, generated measurement
//                  snapshots), each with its reason;
//       DEFERRED — legacy frozen baselines awaiting conversion (BI-3F17B16B
//                  inventory). SHRINK-ONLY: convert a file, remove its row in
//                  the same PR. Never add a NEW baseline here — new baselines
//                  are born budgeted.
//
// An expired budget FAILS CI: the owner must re-review the debt and recommit
// (ideally shrinking via the guard's --update path) rather than let the freeze
// quietly outlive its mandate.
//
//   node scripts/check-no-expired-baseline-budgets.mjs   # check (CI, guard loop)

import { readFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

import {
  parseTxtBudgetHeader,
  readJsonBudget,
  todayISO,
  validateBudget,
} from "./lib/baseline-budget.mjs";

const SCRIPTS_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(SCRIPTS_DIR, "..");

// Files that are NOT frozen-debt budgets — never require owner/expiry.
export const EXEMPT = Object.freeze({
  "scripts/context-economy-baseline.json":
    "deliberately soft plane-3 shape — growth is allowed with a per-entry reason, not a frozen debt budget",
  "scripts/tool-surface-baseline.json":
    "deliberately soft plane-4 shape — growth is allowed with a per-entry reason + recordedAt",
  "scripts/platform-substrate-baseline.json":
    "generated measurement snapshot (gitSha-stamped), regenerated by measure-platform-substrate.mjs",
  "scripts/platform-substrate-runtime-baseline.json":
    "runtime measurement command contract, not a debt list",
  "scripts/mcp-tool-pack-baseline.json":
    "frozen at zero (W9) — any entry at all is a violation, so there is no owned debt to expire",
});

// Legacy frozen baselines inventoried by BI-3F17B16B and not yet converted to
// the budget shape. SHRINK-ONLY. Converting one = add owner/expiry metadata
// (and teach its guard's --update path to preserve it), then delete its row.
export const DEFERRED = Object.freeze([
  "scripts/archetype-completeness-baseline.txt",
  "scripts/capability-consumer-baseline.txt",
  "scripts/docs-reference-baseline.txt",
  "scripts/hand-rolled-loading-baseline.txt",
  "scripts/instruction-plane-baseline.txt",
  "scripts/instruction-plane-rule-baseline.txt",
  "scripts/private-identity-baseline.txt",
  "scripts/prose-lint-baseline.json",
  "scripts/provider-local-connector-lifecycle-baseline.json",
  "scripts/reporting-composition-baseline.json",
  "scripts/retired-substrate-baseline.txt",
  "scripts/route-error-baseline.txt",
  "scripts/stewardship-scope-baseline.txt",
  "scripts/superpowers-skill-baseline.txt",
]);

/** Discover the governed baseline files (repo-relative, forward slashes). */
export function discoverBaselineFiles(entries) {
  const files = entries
    .filter((name) => /-baseline\.(json|txt)$/.test(name))
    .map((name) => `scripts/${name}`);
  // The boundary registry is a baseline in registry clothing — same contract.
  files.push("scripts/application-boundaries.json");
  return files.sort();
}

/** Extract the {owner, expiry} budget from a baseline file's text. */
export function budgetForFile(relPath, text) {
  if (relPath.endsWith(".txt")) return parseTxtBudgetHeader(text);
  try {
    return readJsonBudget(JSON.parse(text));
  } catch {
    return { owner: null, expiry: null };
  }
}

/**
 * Pure check core. `readFile(relPath)` returns text or null when unreadable.
 * Returns { failures: string[] }.
 */
export function checkBaselineBudgets({
  discovered,
  readFile,
  exempt = EXEMPT,
  deferred = DEFERRED,
  today = todayISO(),
}) {
  const failures = [];
  const discoveredSet = new Set(discovered);

  for (const rel of Object.keys(exempt)) {
    if (!discoveredSet.has(rel)) failures.push(`${rel}: EXEMPT entry is stale — the file no longer exists; remove the row.`);
  }
  for (const rel of deferred) {
    if (!discoveredSet.has(rel)) failures.push(`${rel}: DEFERRED entry is stale — the file no longer exists; remove the row.`);
  }
  const deferredSet = new Set(deferred);

  for (const rel of discovered) {
    if (rel in exempt) continue;
    const text = readFile(rel);
    if (text === null) {
      failures.push(`${rel}: unreadable baseline file.`);
      continue;
    }
    const budget = budgetForFile(rel, text);
    if (deferredSet.has(rel)) {
      if (budget.owner && budget.expiry) {
        failures.push(
          `${rel}: carries a budget but is still on the DEFERRED roster — remove its DEFERRED row in the same PR (the roster is shrink-only).`,
        );
      }
      continue; // legacy freeze, conversion pending — inventoried, not enforced
    }
    failures.push(...validateBudget(budget, { label: rel, today }));
  }
  return { failures };
}

export function main() {
  const discovered = discoverBaselineFiles(readdirSync(SCRIPTS_DIR));
  const { failures } = checkBaselineBudgets({
    discovered,
    readFile: (rel) => {
      const abs = join(REPO_ROOT, rel);
      if (!existsSync(abs)) return null;
      try {
        return readFileSync(abs, "utf8");
      } catch {
        return null;
      }
    },
  });

  if (failures.length > 0) {
    console.error("Baseline budget guard failed (BI-3F17B16B) — baselines are owned, expiring budgets:");
    for (const f of failures) console.error(`  - ${f}`);
    console.error("");
    console.error("House shape: scripts/fk-index-coverage-baseline.json (JSON) / scripts/module-size-baseline.txt (txt header).");
    console.error("Helpers: scripts/lib/baseline-budget.mjs. Never park a NEW baseline on the DEFERRED roster.");
    process.exit(1);
  }

  const enforced = discovered.filter((f) => !(f in EXEMPT) && !DEFERRED.includes(f));
  console.log(
    `Baseline budgets OK — ${enforced.length} budgeted, ${DEFERRED.length} deferred legacy (shrink-only), ` +
      `${Object.keys(EXEMPT).length} exempt-by-shape.`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
