#!/usr/bin/env node

// Canonical keep/reduce/absorb policy for direct external dependencies.
// Decisions live in sbom/dependency-allowlist.json; this module validates that
// ledger against the current manifests and renders its deterministic human view.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { listAllDirectDependencies } from "./direct-dependencies.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const DEPENDENCY_DISPOSITION_MATRIX_PATH = join(ROOT, "sbom", "dependency-disposition-matrix.md");
export const VALID_DISPOSITIONS = Object.freeze(["keep", "reduce", "absorb"]);
const VALID = new Set(VALID_DISPOSITIONS);
const FIRST_PARTY_PROTOCOL = /^(?:workspace|file|link):/;
const ACTIONABLE_ROUTE = /^(?:BI-[A-Z0-9]+|DI-[A-Z0-9]+|PR #\d+|#\d+|docs\/superpowers\/(?:plans|specs)\/)/;

function sorted(values) {
  return [...(values ?? [])].map(String).sort((a, b) => a.localeCompare(b));
}

function isExternalRegistryDependency(info) {
  return sorted(info?.versions).some((version) => version && !FIRST_PARTY_PROTOCOL.test(version));
}

export function externalDependencyNames(current) {
  return [...current.entries()]
    .filter(([, info]) => isExternalRegistryDependency(info))
    .map(([name]) => name)
    .sort((a, b) => a.localeCompare(b));
}

export function validateDependencyDispositions(current, allowlist) {
  const dependencies = allowlist?.dependencies ?? {};
  const issues = [];

  for (const name of externalDependencyNames(current)) {
    const entry = dependencies[name] ?? {};
    if (!Object.hasOwn(entry, "disposition")) {
      issues.push({ name, code: "missing-disposition", message: "no keep/reduce/absorb disposition is recorded" });
      continue;
    }
    if (!VALID.has(entry.disposition)) {
      issues.push({ name, code: "invalid-disposition", message: `disposition ${JSON.stringify(entry.disposition)} is not keep, reduce, or absorb` });
      continue;
    }
    if (typeof entry.rationale !== "string" || !entry.rationale.trim()) {
      issues.push({ name, code: "missing-rationale", message: "the disposition has no rationale" });
    }
    const evidence = Array.isArray(entry.evidence) ? entry.evidence.filter((ref) => typeof ref === "string" && ref.trim()) : [];
    if (!evidence.length) {
      issues.push({ name, code: "missing-evidence", message: "the disposition has no evidence reference" });
    } else if (entry.disposition !== "keep" && !evidence.some((ref) => ACTIONABLE_ROUTE.test(ref))) {
      issues.push({ name, code: "missing-route-evidence", message: "reduce/absorb evidence does not name a BI, decision, PR, plan, or spec" });
    }
  }

  return issues.sort((a, b) => a.name.localeCompare(b.name) || a.code.localeCompare(b.code));
}

function markdownCell(value) {
  return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function issueSummary(issues) {
  return issues.map(({ name, code, message }) => `${name}: ${code} (${message})`).join("; ");
}

export function renderDependencyDispositionMatrix(current, allowlist) {
  const issues = validateDependencyDispositions(current, allowlist);
  if (issues.length) throw new Error(`Cannot render an incomplete dependency disposition ledger: ${issueSummary(issues)}`);

  const names = externalDependencyNames(current);
  const counts = Object.fromEntries(VALID_DISPOSITIONS.map((value) => [value, 0]));
  for (const name of names) counts[allowlist.dependencies[name].disposition] += 1;

  const lines = [
    "# Direct External Dependency Disposition Matrix",
    "",
    "> Generated by `scripts/sbom/dependency-dispositions.mjs` from the canonical",
    "> `sbom/dependency-allowlist.json` decisions joined to current lockfile-root",
    "> manifests. Do not edit this file by hand.",
    "",
    "`keep` is the default rent posture when upstream maintenance is preferable and no approved replacement route exists. `reduce` means narrow, consolidate or remove usage through the cited route. `absorb` means replace the external capability with the cited first-party substrate. Every dependency change updates the ledger and regenerates this matrix in the same PR.",
    "",
    "## Summary",
    "",
    "| Disposition | Packages |",
    "| --- | ---: |",
    `| Keep | ${counts.keep} |`,
    `| Reduce | ${counts.reduce} |`,
    `| Absorb | ${counts.absorb} |`,
    `| **Total** | **${names.length}** |`,
    "",
    "## Package decisions",
    "",
    "| Package | Workspaces | Kinds | Resolved direct versions | Disposition | Rationale | Evidence |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  ];

  for (const name of names) {
    const info = current.get(name);
    const entry = allowlist.dependencies[name];
    lines.push(
      `| \`${markdownCell(name)}\` | ${markdownCell(sorted(info.workspaces).join(", "))} | ${markdownCell(sorted(info.kinds).join(", "))} | ${markdownCell(sorted(info.versions).join(", "))} | **${entry.disposition}** | ${markdownCell(entry.rationale.trim())} | ${markdownCell(entry.evidence.join("; "))} |`,
    );
  }

  lines.push("");
  return `${lines.join("\n")}\n`;
}

export function matrixDrift(expected, actual) {
  return expected === actual ? null : "sbom/dependency-disposition-matrix.md is stale; run `node scripts/sbom/dependency-dispositions.mjs --write`";
}

function main() {
  const allowlistPath = join(ROOT, "sbom", "dependency-allowlist.json");
  const allowlist = JSON.parse(readFileSync(allowlistPath, "utf8"));
  const current = listAllDirectDependencies(ROOT);
  let expected;

  try {
    expected = renderDependencyDispositionMatrix(current, allowlist);
  } catch (error) {
    process.stderr.write(`::error::${error.message}\n`);
    process.exitCode = 1;
    return;
  }

  if (process.argv.includes("--write")) {
    writeFileSync(DEPENDENCY_DISPOSITION_MATRIX_PATH, expected);
    process.stdout.write(`Dependency disposition matrix updated: ${DEPENDENCY_DISPOSITION_MATRIX_PATH}\n`);
    return;
  }

  let actual = "";
  try {
    actual = readFileSync(DEPENDENCY_DISPOSITION_MATRIX_PATH, "utf8");
  } catch {
    // Missing output is ordinary drift and uses the same actionable message.
  }
  const drift = matrixDrift(expected, actual);
  if (drift) {
    process.stderr.write(`::error::${drift}\n`);
    process.exitCode = 1;
    return;
  }

  process.stdout.write(`OK — ${externalDependencyNames(current).length} direct external dependency dispositions are complete and the matrix is current.\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  main();
}
