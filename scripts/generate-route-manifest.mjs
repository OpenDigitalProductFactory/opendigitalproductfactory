#!/usr/bin/env node
// Generate the explicit route registry/manifest (BI-8C0F219A).
//
// Emits apps/web/lib/navigation/route-manifest.generated.json — a point-in-time
// enumeration of every App Router page route with its classification against the
// canonical portal navigation model. The nav model remains the single source of
// truth for a classified route's audience + destination-kind; this manifest is
// the census layer that makes "which routes are NOT yet in the registry" explicit.
//
//   node scripts/generate-route-manifest.mjs

import { writeFileSync } from "node:fs";
import { buildRouteManifest, unclassifiedRoutes } from "./lib/route-classification.mjs";

const OUT = "apps/web/lib/navigation/route-manifest.generated.json";

const manifest = buildRouteManifest();
const counts = manifest.reduce((acc, r) => {
  acc[r.classification] = (acc[r.classification] ?? 0) + 1;
  return acc;
}, {});

const payload = {
  // NOTE: generated by scripts/generate-route-manifest.mjs — do not hand-edit.
  // The canonical nav model (apps/web/lib/navigation/portal-navigation-model.ts)
  // owns each classified route's audience + destination-kind.
  source: "apps/web/app x apps/web/lib/navigation/portal-navigation-model.ts",
  totalPageRoutes: manifest.length,
  distinctUnclassifiedRoutes: unclassifiedRoutes(manifest).length,
  counts,
  routes: manifest,
};

writeFileSync(OUT, JSON.stringify(payload, null, 2) + "\n");
console.log(`[route-manifest] wrote ${OUT}: ${manifest.length} page routes`, counts);
