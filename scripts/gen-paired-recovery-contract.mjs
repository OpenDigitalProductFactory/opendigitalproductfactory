import { readFile, writeFile } from "node:fs/promises";
import { parseArgs } from "node:util";
import { scriptArgv } from "./lib/script-argv.mjs";

const { values } = parseArgs({ args: scriptArgv(), options: { check: { type: "boolean" } } });
const source = new URL("../packages/integration-shared/src/paired-recovery-contract.cjs", import.meta.url);
const destination = new URL("./lib/paired-recovery-contract.generated.cjs", import.meta.url);
const generated = "// Generated by scripts/gen-paired-recovery-contract.mjs. Do not edit.\n" + await readFile(source, "utf8");
if (values.check) {
  if (await readFile(destination, "utf8").catch(() => "") !== generated) {
    console.error("The promoter's paired-recovery contract is stale. Run node scripts/gen-paired-recovery-contract.mjs.");
    process.exitCode = 1;
  }
} else {
  await writeFile(destination, generated);
}
