#!/usr/bin/env node
// scripts/check-retired-substrate.mjs
//
// THE PROBLEM IT FIXES: a page can name a service the platform no longer runs,
// and nothing notices. BET-5 retired Neo4j and Qdrant onto PostgreSQL; the
// published platform overview kept presenting Neo4j as a live datastore, and the
// disaster-recovery runbook kept instructing operators — mid-incident — to run
// `restore-neo4j.sh` and `docker compose up -d postgres neo4j qdrant` against
// containers that had been decommissioned. Both survived every existing gate.
//
// WHY THE DOC-IMPACT GRAPH IS NOT ENOUGH: those edges are OPT-IN. A page is
// protected only if somebody remembered to add `relatedCode:` to it — the same
// "someone must remember" failure mode that caused the miss. This gate needs no
// cooperation from the page. It reads the words that are actually published.
//
// THE CONTRACT: every live doc mentioning a retired term must be listed in
// scripts/retired-substrate-baseline.txt. Ratcheted like the other doc gates —
// pre-existing mentions are grandfathered and can only shrink; a NET-NEW
// (page, term) pair fails. Retiring something new is one line in
// scripts/retired-substrate.json, and every stale page surfaces at once.
//
// DELIBERATELY SCANS FENCED CODE BLOCKS. The most dangerous instance was a
// copy-pasteable command block in an incident runbook. A gate that skipped code
// fences would have missed precisely the case that mattered most.
//
//   node scripts/check-retired-substrate.mjs           # fail on net-new mentions
//   node scripts/check-retired-substrate.mjs --update  # retighten the baseline
//
// Zero external dependencies, in keeping with the other doc gates.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { publishedDocFiles } from "./lib/published-doc-roots.mjs";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY = path.join(REPO_ROOT, "scripts", "retired-substrate.json");
const BASELINE = path.join(REPO_ROOT, "scripts", "retired-substrate-baseline.txt");

export function loadRegistry(json) {
  const parsed = typeof json === "string" ? JSON.parse(json) : json;
  const entries = parsed.retired ?? [];
  for (const e of entries) {
    if (!e.term || typeof e.term !== "string") {
      throw new Error(`[retired-substrate] registry entry missing a "term": ${JSON.stringify(e)}`);
    }
  }
  return entries;
}

/**
 * Find retired terms in `markdown`. Matches on word boundaries and
 * case-insensitively, so "Neo4j", "neo4j-driver" and "NEO4J_URL" all count —
 * a stale env var name is as misleading as stale prose.
 *
 * @returns {Array<{term: string, line: number}>} first hit per term, in registry order
 */
export function findRetiredMentions(markdown, entries) {
  const lines = markdown.split("\n");
  const hits = [];
  for (const { term } of entries) {
    // Escape regex metacharacters, then bound on a non-alphanumeric char or a
    // string edge. Note `_` is deliberately a BOUNDARY, not part of the word:
    // a doc telling you to set NEO4J_URL is exactly as stale as one telling you
    // to start the container, so that must match. Requiring a non-alphanumeric
    // on both sides still keeps "neo4jsomething" from firing.
    const safe = term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp(`(^|[^A-Za-z0-9])${safe}([^A-Za-z0-9]|$)`, "i");
    for (let i = 0; i < lines.length; i++) {
      if (re.test(lines[i])) {
        hits.push({ term, line: i + 1 });
        break;
      }
    }
  }
  return hits;
}

/** One stable line per (page, term) pair. */
export function baselineKey(docPath, term) {
  return `${docPath}\t${term}`;
}

export function parseBaseline(text) {
  return new Set(
    text
      .split("\n")
      .map((l) => l.trim())
      .filter((l) => l && !l.startsWith("#"))
      // Tolerate either a tab or runs of spaces as the separator.
      .map((l) => l.replace(/\s+/g, "\t")),
  );
}

export function serializeBaseline(keys) {
  const header = [
    "# Generated by scripts/check-retired-substrate.mjs --update",
    "#",
    "# Live docs that still name retired substrate (see scripts/retired-substrate.json).",
    "# One <doc-path>\\t<term> pair per line. This list is a RATCHET: it may shrink,",
    "# never grow. A net-new pair fails CI.",
    "#",
    "# A pair listed here is a claim that the mention is deliberate historical",
    "# context (\"this layer used to be Neo4j\"), not a live instruction. If you",
    "# cannot make that claim about a line, fix the doc instead of baselining it.",
    "",
  ].join("\n");
  return `${header}${[...keys].sort().join("\n")}\n`;
}

export function computeFindings(docs, entries, readFile) {
  // No page is exempt by path — not even the one documenting this gate. A page
  // that must name a retired term goes in the baseline, where it stays visible,
  // rather than into a hardcoded exclusion nobody reviews again.
  const found = [];
  for (const docPath of docs) {
    for (const hit of findRetiredMentions(readFile(docPath), entries)) {
      found.push({ docPath, ...hit });
    }
  }
  return found;
}

function main() {
  const update = process.argv.includes("--update");
  const entries = loadRegistry(fs.readFileSync(REGISTRY, "utf-8"));
  const docs = publishedDocFiles(REPO_ROOT);
  const readFile = (p) => fs.readFileSync(path.join(REPO_ROOT, p), "utf-8");
  const findings = computeFindings(docs, entries, readFile);
  const currentKeys = new Set(findings.map((f) => baselineKey(f.docPath, f.term)));

  if (update) {
    fs.writeFileSync(BASELINE, serializeBaseline(currentKeys));
    console.log(`[retired-substrate] baseline retightened — ${currentKeys.size} grandfathered mention(s).`);
    return;
  }

  const baseline = fs.existsSync(BASELINE) ? parseBaseline(fs.readFileSync(BASELINE, "utf-8")) : new Set();
  const netNew = findings.filter((f) => !baseline.has(baselineKey(f.docPath, f.term)));
  const byTerm = new Map(entries.map((e) => [e.term, e]));

  if (netNew.length === 0) {
    const stale = [...baseline].filter((k) => !currentKeys.has(k)).length;
    console.log(
      `[retired-substrate] OK — no net-new mentions of retired substrate (${currentKeys.size} grandfathered${stale ? `, ${stale} now fixed: run --update to retighten` : ""}).`,
    );
    return;
  }

  console.error("");
  console.error(`[retired-substrate] FAILED — ${netNew.length} live doc mention(s) of RETIRED substrate:`);
  console.error("");
  for (const f of netNew) {
    const meta = byTerm.get(f.term) ?? {};
    console.error(`  • ${f.docPath}:${f.line}`);
    console.error(`      names "${f.term}", retired by ${meta.retiredBy ?? "an earlier change"}`);
    if (meta.replacement) console.error(`      use instead: ${meta.replacement}`);
  }
  console.error("");
  console.error("A published page names infrastructure the platform no longer runs. On an");
  console.error("architecture page that misinforms; in a runbook it can send an operator to");
  console.error("restore a database that does not exist.");
  console.error("");
  console.error("To resolve, do ONE of:");
  console.error("  1. Update the page to describe what actually runs today (usually right).");
  console.error("  2. If the mention is deliberate historical context, baseline it:");
  console.error("       node scripts/check-retired-substrate.mjs --update");
  console.error("     and commit scripts/retired-substrate-baseline.txt.");
  console.error("");
  process.exit(1);
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("check-retired-substrate.mjs")) {
  main();
}
