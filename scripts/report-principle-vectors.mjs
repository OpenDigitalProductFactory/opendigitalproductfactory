#!/usr/bin/env node
// scripts/report-principle-vectors.mjs
//
// BI-4AD74F86. Characterize the principle dimension vectors as a corpus.
//
// Every vector was authored in isolation against prose guidance, so drift is
// the expected state rather than a hypothesis. Two sibling items propose rules
// for these vectors — anchoring magnitudes, and checking for padding — and both
// are proposals about a corpus nobody has looked at as a whole. Per
// `verify-substrate-before-proposing-new`, measure first.
//
// This script CHANGES NOTHING. It reads the corpus and prints what is there.
//
// One property shapes every number below. Alignment is scale-invariant:
//
//     alignment = Σ option[dim]·vector[dim] / Σ |vector[dim]|
//
// so multiplying a whole vector by a positive constant changes nothing. Only
// the RATIOS within one vector carry meaning, and `principleWeight` is the only
// knob that scales a principle's contribution. Comparing a raw magnitude across
// two principles is therefore not meaningful, and this report does not do it —
// it reports each axis's SHARE of its own vector, which is scale-invariant too.

import { readFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { isEntryModule } from "./lib/entry-module.mjs";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(SCRIPT_DIR, "..");
const PRINCIPLES_DIR = join(REPO_ROOT, "docs", "founder-kernel", "wiki", "principles");
const TAXONOMY_PATH = join(REPO_ROOT, "packages", "db", "src", "wiki-taxonomy.ts");

function parseNamedStringArray(source, name) {
  const start = source.indexOf(`${name} = [`);
  if (start === -1) throw new Error(`${name} not found in wiki-taxonomy.ts`);
  const end = source.indexOf("]", start);
  const body = source
    .slice(start, end)
    .split("\n")
    .map((line) => line.replace(/\/\/.*$/, ""))
    .join("\n");
  return [...body.matchAll(/"([a-z_]+)"/g)].map((m) => m[1]);
}

/** Frontmatter fields this report needs. Deliberately tolerant: a page it cannot parse is REPORTED, never skipped silently. */
export function parsePrinciple(slug, text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return { slug, error: "no frontmatter" };
  const fm = match[1];

  const scalar = (key) => {
    const m = fm.match(new RegExp(`^${key}:\\s*(.+)$`, "m"));
    return m ? m[1].trim() : null;
  };

  const vectorRaw = scalar("principleDimensionVector");
  let vector = null;
  let vectorError = null;
  if (vectorRaw) {
    try {
      vector = JSON.parse(vectorRaw);
    } catch {
      vectorError = "unparseable principleDimensionVector";
    }
  }

  const weightRaw = scalar("principleWeight");
  return {
    slug,
    tier: scalar("principleTier"),
    weight: weightRaw === null ? null : Number(weightRaw),
    weightRationale: Boolean(scalar("principleWeightRationale")),
    vector,
    vectorError,
  };
}

export function summarize({ principles, dimensions, costDimensions }) {
  const axisUse = new Map(dimensions.map((d) => [d, []]));
  const unknownAxes = new Map();
  const signViolations = [];
  const widths = [];
  const noVector = [];
  const parseErrors = [];

  for (const p of principles) {
    if (p.error || p.vectorError) {
      parseErrors.push({ slug: p.slug, reason: p.error || p.vectorError });
      continue;
    }
    if (!p.vector) {
      noVector.push({ slug: p.slug, tier: p.tier });
      continue;
    }

    const entries = Object.entries(p.vector);
    widths.push({ slug: p.slug, tier: p.tier, width: entries.length });

    // Scale-invariant share: |w| over the sum of |w| in the SAME vector.
    const total = entries.reduce((sum, [, w]) => sum + Math.abs(Number(w)), 0) || 1;

    for (const [axis, weightValue] of entries) {
      const weight = Number(weightValue);
      if (!axisUse.has(axis)) {
        unknownAxes.set(axis, [...(unknownAxes.get(axis) || []), p.slug]);
        continue;
      }
      axisUse.get(axis).push({ slug: p.slug, weight, share: Math.abs(weight) / total });
      if (costDimensions.includes(axis) && weight > 0) {
        signViolations.push({ slug: p.slug, axis, weight });
      }
    }
  }

  return { axisUse, unknownAxes, signViolations, widths, noVector, parseErrors };
}

function pct(n, d) {
  return d === 0 ? "0%" : `${Math.round((n / d) * 100)}%`;
}

function render(summary, { total, dimensions, costDimensions }) {
  const { axisUse, unknownAxes, signViolations, widths, noVector, parseErrors } = summary;
  const out = [];
  const vectored = widths.length;

  out.push("# Principle dimension vectors — corpus report");
  out.push("");
  out.push("> Generated by `scripts/report-principle-vectors.mjs` (BI-4AD74F86). Read-only.");
  out.push("");
  out.push(
    "Alignment is scale-invariant, so a raw magnitude is not comparable across principles and this "
      + "report never compares one. Each axis is reported by its **share of its own vector**, which is "
      + "scale-invariant. `principleWeight` is the only knob that scales a principle's contribution.",
  );
  out.push("");
  out.push(`- Principle pages: **${total}**`);
  out.push(`- Carrying a vector: **${vectored}**`);
  out.push(`- No vector: **${noVector.length}**`);
  out.push(`- Unparseable: **${parseErrors.length}**`);
  out.push("");

  out.push("## Axis usage");
  out.push("");
  out.push("A dimension used by one principle is a dimension with no shared meaning to calibrate against.");
  out.push("");
  out.push("| Axis | Cost? | Principles | Median share of its vector |");
  out.push("|---|---|---|---|");
  const rows = dimensions
    .map((axis) => {
      const uses = axisUse.get(axis) || [];
      const shares = uses.map((u) => u.share).sort((a, b) => a - b);
      const median = shares.length
        ? shares[Math.floor(shares.length / 2)]
        : null;
      return { axis, count: uses.length, median };
    })
    .sort((a, b) => b.count - a.count);
  for (const r of rows) {
    out.push(
      `| \`${r.axis}\` | ${costDimensions.includes(r.axis) ? "cost" : ""} | ${r.count} | `
        + `${r.median === null ? "—" : `${Math.round(r.median * 100)}%`} |`,
    );
  }
  out.push("");
  const unused = rows.filter((r) => r.count === 0);
  if (unused.length) {
    out.push(`**Unused: ${unused.length}** — ${unused.map((r) => `\`${r.axis}\``).join(", ")}.`);
    out.push("");
  }

  out.push("## Vector width");
  out.push("");
  out.push(
    "`AUTHORING.md` §8B says to focus a vector on the one or two axes that characterize the rule, "
      + "and warns that padding drags canonical margins. This is the population that would fail a "
      + "padding check.",
  );
  out.push("");
  const byWidth = new Map();
  for (const w of widths) byWidth.set(w.width, (byWidth.get(w.width) || 0) + 1);
  out.push("| Axes in vector | Principles | Share |");
  out.push("|---|---|---|");
  for (const width of [...byWidth.keys()].sort((a, b) => a - b)) {
    out.push(`| ${width} | ${byWidth.get(width)} | ${pct(byWidth.get(width), vectored)} |`);
  }
  const over = widths.filter((w) => w.width > 2);
  out.push("");
  out.push(`**Above the guidance (3+ axes): ${over.length} of ${vectored} (${pct(over.length, vectored)}).**`);
  out.push("");

  out.push("## Sign correctness");
  out.push("");
  if (signViolations.length === 0) {
    out.push(
      `No cost axis carries a positive weight. The sign guard in \`seed-wiki-kernel.test.ts\` covers `
        + `all ${costDimensions.length} and is holding.`,
    );
  } else {
    out.push("| Principle | Axis | Weight |");
    out.push("|---|---|---|");
    for (const v of signViolations) out.push(`| \`${v.slug}\` | \`${v.axis}\` | ${v.weight} |`);
  }
  out.push("");

  if (unknownAxes.size) {
    out.push("## Axes not in the registry");
    out.push("");
    out.push("These would be rejected by the seed walker. Their presence here means a page is unseedable.");
    out.push("");
    for (const [axis, slugs] of unknownAxes) out.push(`- \`${axis}\` — ${slugs.join(", ")}`);
    out.push("");
  }

  if (noVector.length) {
    out.push("## Pages with no vector");
    out.push("");
    out.push("Blocking for `commandment` tier, warn-only for `core`.");
    out.push("");
    for (const p of noVector) out.push(`- \`${p.slug}\` (${p.tier ?? "tier unset"})`);
    out.push("");
  }

  if (parseErrors.length) {
    out.push("## Could not be read");
    out.push("");
    for (const e of parseErrors) out.push(`- \`${e.slug}\` — ${e.reason}`);
    out.push("");
  }

  out.push("## What this report does not tell you");
  out.push("");
  out.push(
    "- **Whether a ratio is right.** Nothing anchors ratios, which is BI-EF97E987. This measures the "
      + "spread; it cannot judge it.",
  );
  out.push(
    "- **Whether an axis belongs in a vector.** That needs the orthogonality statement proposed in "
      + "BI-4CF7DCC4.",
  );
  out.push(
    "- **Which principles actually move a decision.** That needs the golden-decisions panel, which "
      + "scores a curated scenario set rather than the whole space.",
  );
  return out.join("\n");
}

function main() {
  const taxonomy = readFileSync(TAXONOMY_PATH, "utf8");
  const dimensions = parseNamedStringArray(taxonomy, "PRINCIPLE_DIMENSIONS");
  const costDimensions = parseNamedStringArray(taxonomy, "PRINCIPLE_COST_DIMENSIONS");

  const files = readdirSync(PRINCIPLES_DIR).filter((f) => f.endsWith(".md"));
  const principles = files.map((f) =>
    parsePrinciple(f.replace(/\.md$/, ""), readFileSync(join(PRINCIPLES_DIR, f), "utf8")),
  );

  const summary = summarize({ principles, dimensions, costDimensions });
  process.stdout.write(`${render(summary, { total: principles.length, dimensions, costDimensions })}\n`);
  return 0;
}

if (isEntryModule(import.meta.url)) {
  process.exit(main());
}
