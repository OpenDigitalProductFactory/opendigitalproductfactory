// Converge the gitignored .githooks/pre-push shim (BI-C74F4DE9).
//
// git only ever invokes the hook named `pre-push`, but that file is local:
// git-lfs generates it and .gitignore excludes it, so the repo cannot ship
// enforcement logic in it directly (tracking it would collide with the
// untracked copy in every existing clone). Instead the enforced logic lives in
// the TRACKED .githooks/lib/pre-push-chained.sh (LFS first, then the local-CI
// gate), and postinstall converges the local shim to delegate to it.
//
// Convergence is deliberately conservative:
//   - missing shim                → write the delegating shim
//   - stock git-lfs shim          → replace (LFS behavior preserved inside the
//                                   chained script)
//   - already-delegating shim     → leave untouched (idempotent)
//   - anything else (custom hook) → leave untouched, report "custom" — a
//                                   hand-rolled hook must never be clobbered
//                                   by a package install.

import fs from "node:fs";
import path from "node:path";

export const DELEGATING_SHIM = `#!/bin/sh
# Generated by scripts/set-hooks-path.mjs (postinstall) — do not edit here.
# Real logic (Git LFS + DPF local-CI gate) is tracked at .githooks/lib/pre-push-chained.sh.
exec sh "$(dirname "$0")/lib/pre-push-chained.sh" "$@"
`;

export function classifyPrePushShim(content) {
  if (content == null) return "missing";
  if (content.includes("pre-push-chained.sh")) return "delegating";
  // The stock git-lfs shim: a `command -v git-lfs` guard plus `git lfs
  // pre-push "$@"`, nothing else of substance.
  if (content.includes("git lfs pre-push") && !content.includes("pre-push-gate")) return "lfs-stock";
  return "custom";
}

export function ensurePrePushHook(hooksDir) {
  const shimPath = path.join(hooksDir, "pre-push");
  let existing = null;
  try {
    existing = fs.readFileSync(shimPath, "utf8");
  } catch {
    /* missing */
  }
  const kind = classifyPrePushShim(existing);
  if (kind === "missing" || kind === "lfs-stock") {
    fs.writeFileSync(shimPath, DELEGATING_SHIM, { mode: 0o755 });
    fs.chmodSync(shimPath, 0o755);
    return { action: "written", was: kind };
  }
  if (kind === "delegating") return { action: "unchanged", was: kind };
  return { action: "left-custom", was: kind };
}
