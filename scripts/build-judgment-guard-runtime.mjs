#!/usr/bin/env node
// Deterministic build distribution for the dependency-free Node20 golden guard.
// Canonical implementation: validators judgment sources. Owner @markdbodman,
// BI-4DD124E7. Never edit emitted JavaScript by hand.
import { loadPinnedGuardTypeScript } from "./lib/load-pinned-guard-typescript.mjs";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const ts = loadPinnedGuardTypeScript({ repoRoot: ROOT });
const COMPILER_VERSION = "6.0.3";
export const SOURCE_PATHS = [
  "packages/validators/src/judgment/option-scoring.ts",
  "packages/validators/src/judgment/mcda-quality-gates.ts",
];
export const ARTIFACT_DIRECTORY = "scripts/generated/judgment";
const hash = (text) => createHash("sha256").update(text).digest("hex");
const readSource = (path) => readFileSync(join(ROOT, path), "utf8");
const compilerOptions = {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ES2022,
  newLine: ts.NewLineKind.LineFeed,
  removeComments: false,
  verbatimModuleSyntax: true,
  rewriteRelativeImportExtensions: true,
};

export function buildArtifacts(read = readSource) {
  if (ts.version !== COMPILER_VERSION) throw new Error(`Expected TypeScript ${COMPILER_VERSION}, received ${ts.version}. Reassess generated bytes before changing the pin.`);
  const artifacts = new Map();
  const sources = {};
  artifacts.set(ARTIFACT_DIRECTORY + "/package.json", JSON.stringify({
    private: true, type: "module", license: "Apache-2.0",
  }, null, 2) + "\n");
  for (const path of SOURCE_PATHS) {
    const contents = read(path);
    sources[path] = hash(contents);
    const imports = ts.preProcessFile(contents).importedFiles.map((item) => item.fileName);
    const expected = path.endsWith("/option-scoring.ts") ? ["./mcda-quality-gates.ts"] : [];
    if (JSON.stringify(imports) !== JSON.stringify(expected))
      throw new Error(`Unreviewed runtime dependency in ${path}. Expand the explicit closure before generating.`);
    const output = ts.transpileModule(contents, { compilerOptions, fileName: path, reportDiagnostics: true });
    const errors = (output.diagnostics ?? []).filter((d) => d.category === ts.DiagnosticCategory.Error);
    if (errors.length) throw new Error(errors.map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n")).join("\n"));
    const name = path.slice(path.lastIndexOf("/") + 1, -3) + ".js";
    artifacts.set(ARTIFACT_DIRECTORY + "/" + name,
      `// Generated from ${path} by scripts/build-judgment-guard-runtime.mjs; do not edit.\n` + output.outputText);
  }
  artifacts.set(ARTIFACT_DIRECTORY + "/manifest.json", JSON.stringify({
    schemaVersion: 1,
    owner: "@markdbodman",
    backlogItem: "BI-4DD124E7",
    license: "Apache-2.0",
    compiler: { name: "typescript", version: ts.version, target: "ES2022", module: "ES2022", newLine: "LF", removeComments: false, verbatimModuleSyntax: true, rewriteRelativeImportExtensions: true },
    sources,
    outputs: Object.fromEntries([...artifacts].map(([path, contents]) => [path, hash(contents)])),
    runtimeDependencies: [],
  }, null, 2) + "\n");
  return artifacts;
}

export function staleArtifacts(artifacts, read = (path) => {
  try { return readFileSync(join(ROOT, path), "utf8"); }
  catch (error) { if (error.code === "ENOENT") return undefined; throw error; }
}) {
  return [...artifacts].filter(([path, contents]) => read(path) !== contents).map(([path]) => path);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const artifacts = buildArtifacts();
  if (process.argv.includes("--check")) {
    const stale = staleArtifacts(artifacts);
    if (stale.length) {
      console.error(`Judgment guard runtime is stale: ${stale.join(", ")}. Regenerate with scripts/build-judgment-guard-runtime.mjs.`);
      process.exitCode = 1;
    } else console.log("Judgment guard runtime fresh (canonical source and generated bytes match).");
  } else {
    for (const [path, contents] of artifacts) {
      const target = join(ROOT, path);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, contents);
    }
    console.log(`Wrote ${artifacts.size} judgment guard distribution artifacts.`);
  }
}
