#!/usr/bin/env node
// BI-545943EE: generate the operating contract that the process-spine
// SessionStart hook carries inline when DPF cannot prove its skills are loaded.
//
// The contract is never hand-written. Each line is read from the page that
// states the rule: the `principleDirection` frontmatter of three kernel
// principles, and the AGENTS.md §11 bullet anchored on the doctrine-store rule.
// Any missing or empty source throws; a partial contract is never written.
//
// Output: packages/dpf-skill-pack/hooks/operating-contract.generated.mjs, a
// static module the hook imports (consumer installs carry no docs/, so the hook
// reads no repo files at runtime). Registered with the derived-artifact gate
// (scripts/lib/derived-artifacts-registry.mjs, id "operating-contract").
//
// Usage:
//   node packages/dpf-skill-pack/scripts/generate-operating-contract.mjs          # write
//   node packages/dpf-skill-pack/scripts/generate-operating-contract.mjs --check  # fail if stale

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

export const PRINCIPLE_SOURCES = Object.freeze([
  "docs/founder-kernel/wiki/principles/decisions-belong-to-their-scope.md",
  "docs/founder-kernel/wiki/principles/escalation-is-a-gate-not-a-trust-tier.md",
  "docs/founder-kernel/wiki/principles/consult-scopes-before-asking.md",
]);

export const AGENTS_SOURCE = "AGENTS.md";
export const AGENTS_ANCHOR = "**Kernel principles (Surface C) are the durable doctrine store.**";
export const AGENTS_LABEL = "AGENTS.md §11";

export const GENERATED_MODULE_PATH = "packages/dpf-skill-pack/hooks/operating-contract.generated.mjs";

const CONTRACT_HEADER = "Operating contract (inline because DPF cannot prove its skills are loaded):";
// Fixed template text, not doctrine: how to dereference the slugs above.
const CONTRACT_FOOTER = "Before inferring doctrine from source, read the page: wiki_query <slug>.";

function readSource(repoRoot, rel) {
  const abs = join(repoRoot, rel);
  if (!existsSync(abs)) {
    throw new Error(`operating contract source missing: ${rel}`);
  }
  return readFileSync(abs, "utf8").replace(/\r\n/g, "\n");
}

function unquote(value) {
  const v = value.trim();
  if (v.length >= 2 && ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'")))) {
    return v.slice(1, -1);
  }
  return v;
}

/** Read a top-level scalar from YAML frontmatter; supports plain, quoted, and folded (>-) values. */
export function readFrontmatterScalar(markdown, key) {
  const match = /^---\n([\s\S]*?)\n---(?:\n|$)/.exec(markdown);
  if (!match) return null;
  const lines = match[1].split("\n");
  for (let i = 0; i < lines.length; i += 1) {
    const m = new RegExp(`^${key}:(.*)$`).exec(lines[i]);
    if (!m) continue;
    const raw = m[1].trim();
    if (/^[>|][-+]?$/.test(raw)) {
      const parts = [];
      for (let j = i + 1; j < lines.length && /^\s+\S/.test(lines[j]); j += 1) {
        parts.push(lines[j].trim());
      }
      return parts.join(" ").trim();
    }
    return unquote(raw);
  }
  return null;
}

function principleLine(repoRoot, rel) {
  const text = readSource(repoRoot, rel);
  const direction = readFrontmatterScalar(text, "principleDirection");
  if (!direction) {
    throw new Error(`operating contract source has no principleDirection: ${rel}`);
  }
  const slug = readFrontmatterScalar(text, "slug") || `principles/${basename(rel, ".md")}`;
  return `- ${slug}: ${direction}`;
}

function agentsLine(repoRoot) {
  const text = readSource(repoRoot, AGENTS_SOURCE);
  const bullet = text.split("\n").find((line) => line.startsWith(`- ${AGENTS_ANCHOR}`));
  if (!bullet) {
    throw new Error(`operating contract source missing: ${AGENTS_SOURCE} bullet anchored on ${AGENTS_ANCHOR}`);
  }
  const rule = bullet.slice(2).replace(/\*\*/g, "").trim();
  if (!rule) {
    throw new Error(`operating contract source is empty: ${AGENTS_SOURCE} bullet anchored on ${AGENTS_ANCHOR}`);
  }
  return `- ${AGENTS_LABEL}: ${rule}`;
}

/** Build every contract line, or throw. Never returns a partial contract. */
export function buildOperatingContractLines(repoRoot = REPO_ROOT) {
  const entries = PRINCIPLE_SOURCES.map((rel) => principleLine(repoRoot, rel));
  entries.push(agentsLine(repoRoot));
  return [CONTRACT_HEADER, ...entries, CONTRACT_FOOTER];
}

export function renderGeneratedModule(lines) {
  const body = lines.map((line) => `  ${JSON.stringify(line)},`).join("\n");
  return [
    "// GENERATED by packages/dpf-skill-pack/scripts/generate-operating-contract.mjs -- do not edit.",
    "// Sources (edit these, then regenerate; pre-commit does it for you):",
    ...PRINCIPLE_SOURCES.map((rel) => `//   ${rel} (principleDirection)`),
    `//   ${AGENTS_SOURCE} (the bullet anchored on ${AGENTS_ANCHOR})`,
    "// BI-545943EE.",
    "",
    "export const OPERATING_CONTRACT_LINES = Object.freeze([",
    body,
    "]);",
    "",
  ].join("\n");
}

function main(argv) {
  const check = argv.includes("--check");
  const next = renderGeneratedModule(buildOperatingContractLines(REPO_ROOT));
  const outPath = join(REPO_ROOT, GENERATED_MODULE_PATH);
  if (check) {
    const current = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== next) {
      console.error(
        `${GENERATED_MODULE_PATH} is stale. Run: node packages/dpf-skill-pack/scripts/generate-operating-contract.mjs`,
      );
      process.exit(1);
    }
    console.log("operating contract fresh.");
    return;
  }
  writeFileSync(outPath, next);
  console.log(`Wrote ${GENERATED_MODULE_PATH}.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  main(process.argv.slice(2));
}
