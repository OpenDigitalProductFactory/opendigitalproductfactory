import { bearerHeaderRequiredFor } from "./client-capability-rules.cjs";
import { CLIENT_CAPABILITY_PROFILE } from "./client-capability-profile.generated";

/**
 * Whether a DPF MCP client config for `endpoint` must carry the bearer-header
 * fallback (BI-46B636B0).
 *
 * OAuth support is client-specific. Since BI-64795FD0 this is a pure function
 * of the client capability profile (packages/dpf-skill-pack/client-capabilities.json)
 * and the endpoint: OAuth is used only where the profile states the client can
 * complete it on that transport (https, or loopback http). Anything unproven
 * keeps the bearer. A generated configuration is not evidence of authenticated
 * readiness.
 *
 * Both writers of the client config (the portal's setup snippets and the
 * toolchain bootstrap planner) consult this one predicate; the SessionStart
 * health hooks apply the same rule to diagnose a config that cannot
 * authenticate. Its fixture, mcp-credential-policy-cases.json, is generated
 * from the same profile.
 */
export type McpClient = "codex" | "claude" | "vscode" | "grok" | "antigravity";
export type McpAuthMode = "oauth" | "legacy";

export function mcpClientBearerHeaderRequired(endpoint: string, client: McpClient = "claude", authMode: McpAuthMode = "oauth"): boolean {
  return bearerHeaderRequiredFor(CLIENT_CAPABILITY_PROFILE, endpoint, client, authMode);
}

/**
 * The public OAuth scopes a DPF development client pins when it authorizes
 * over https (BI-3D2FD68C).
 *
 * Claude Code requests exactly the advertised scope set when nothing is
 * pinned. The portal now advertises `dpf.read dpf.work dpf.build` in its
 * protected-resource metadata (`ADVERTISED_SCOPES` in
 * apps/web/lib/auth/oauth-scope-map.ts, BI-CE5F8C0A), so the pin and the
 * advertisement agree today. The pin stays because a narrower advertisement
 * would otherwise strand Claude read-only for good: progressive disclosure
 * hides every write tool, so the `insufficient_scope` step-up never fires.
 * The consent screen lists each pinned scope as a named checkbox the operator
 * approves.
 *
 * Since BI-5201141C the one Claude connector that carries the pin is the
 * dpf-platform plugin descriptor (packages/dpf-skill-pack/claude.mcp.json,
 * generated by the skill pack's Python mirror of this constant); no writer
 * puts a project .mcp.json beside it on https.
 *
 * The set is the smallest that covers platform-development work: backlog,
 * workroom, evidence and lease writes (`dpf.work`) and execution evidence
 * (`dpf.build`). `dpf.business`, `dpf.operate` and `dpf.admin` are consent
 * decisions an operator makes on purpose, never a default a bootstrap makes
 * for them. Every value must be a member of the portal's public scope
 * vocabulary; `apps/web/lib/auth/mcp-setup-snippets.test.ts` asserts that.
 *
 * The portal's setup snippets and the toolchain bootstrap planner consult
 * this one constant.
 */
export const MCP_CLIENT_OAUTH_SCOPE_PIN = "dpf.read dpf.work dpf.build";

/**
 * The `oauth.scopes` value a client entry for `endpoint` carries: the pin when
 * the client is Claude Code and its credential path is OAuth (no bearer header
 * required for that client and mode), nothing otherwise. Only Claude Code
 * receives this pin. Grok uses client_credentials and bearer_token_file
 * (design 12.4.7), not the browser oauth_scopes field. Codex, VS Code and
 * Antigravity do not read oauth.scopes either.
 */
export function mcpClientOAuthScopePin(
  endpoint: string,
  client: McpClient = "claude",
  authMode: McpAuthMode = "oauth",
): string | null {
  if (client !== "claude") return null;
  return mcpClientBearerHeaderRequired(endpoint, client, authMode) ? null : MCP_CLIENT_OAUTH_SCOPE_PIN;
}
